const ROMAN: Record<Level, string> = { 1: "I", 2: "II", 3: "III" };

function levelLabel(levels: Level[]) {
  const min = Math.min(...levels) as Level;
  const max = Math.max(...levels) as Level;
  return min === max ? ROMAN[min] : `${ROMAN[min]}–${ROMAN[max]}`;
}

/** Какие предметы ЕГЭ ближе всего к профилю олимпиады — для фильтра «по моим предметам». */
function profileSubjects(profile: string): SubjectId[] {
  const p = profile.toLowerCase();
  const out = new Set<SubjectId>();
  if (/финансов/.test(p)) out.add("soc");
  if (/математ|вероятност|криптограф/.test(p)) out.add("math");
  if (/физик|астроном|инженер|техник|энергет|робот|беспилот|авиац|космич|приборо|наносистем|фотоник|транспорт/.test(p)) out.add("phys");
  if (/информат|программ|искусствен|данн|кибер|компьютер|информационн|цифров|мобильн|виртуальн|беспроводн|коммуникац/.test(p)) out.add("inf");
  if (/хими/.test(p)) out.add("chem");
  if (/биолог|генет|медицин|эколог|агро|биотех|нейро/.test(p)) out.add("bio");
  if (/обществ|прав|экономик|политолог|журналист|гуманитарн|международн|социолог|государственност|педагог|образован|культуролог/.test(p)) out.add("soc");
  if (/истори(?!я искусств)/.test(p)) out.add("hist");
  if (/литерат|филолог/.test(p)) out.add("lit");
  if (/русск/.test(p)) out.add("rus");
  if (/географ|геолог|науки о земле/.test(p)) out.add("geo");
  if (/иностранн|лингвист|восточн|востоковед/.test(p)) out.add("eng");
  return [...out];
}

